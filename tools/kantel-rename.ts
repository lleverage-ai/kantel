type Keep = {
	/** What is kept, as a regular expression with the `g` flag. */
	readonly pattern: RegExp;
	readonly reason: string;
	/** Only in these files; everywhere when absent. */
	readonly paths?: RegExp;
};

type Rule = {
	readonly id: string;
	readonly pattern: RegExp;
	/** The replacement. `keep` marks text the later rules must not touch. */
	readonly replace: (keep: (text: string) => string, ...match: string[]) => string;
	readonly paths?: RegExp;
	/** Also counted by `--check`: a match left after KEEP is a miss. */
	readonly target?: boolean;
};

