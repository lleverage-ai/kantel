#!/usr/bin/env node
/**
 * The Harbour → Kantel rename (TASK-4231, PR 2), as a deterministic codemod over the repository's tracked text files.
 *
 *   node tools/kantel-rename.ts            dry run: what would change, per rule and per file
 *   node tools/kantel-rename.ts --write    apply it (and `git mv` the files whose names change)
 *   node tools/kantel-rename.ts --check    exit 1 if anything the rename targets is left outside the keep-list
 *
 * It renames what is only a name: the package scope (`@harbour/*` → `@kantel/*`), `HARBOUR_*` environment variables
 * and constants (→ `KANTEL_*`), `Harbour` in copy, docs, comments, types and identifiers (→ `Kantel`), camel-case
 * `harbourX` identifiers, the CSS namespace (`--hb-*` → `--kt-*`, `hb-*` classes → `kt-*`, `data-hb-*` →
 * `data-kt-*`) and a few file names. Partan, the open-source name the public docs used for a day, becomes Kantel too.
 *
 * What isn't only a name was done by hand, in the commit after this one's output: the `KANTEL_*` → `HARBOUR_*`
 * fallback at every entry point, browser storage moving from `harbour.*` to `kantel.*` keys, themes and theme CSS
 * saved with `--hb-*` names, the Durable Object classes exported under their deployed names, the tunnel CLI's old
 * command and flag, and the docs' sentences about the old name. Lines about that layer say "before the rename" or
 * TASK-4231, and KEEP leaves the old names on them alone.
 *
 * It leaves alone what something outside this checkout already holds: deployed Cloudflare names, wire headers,
 * persisted keys, schemas and formats. Those are in KEEP below, each with its reason, and a match of KEEP is never
 * rewritten. Lowercase `harbour` on its own (a Worker name, a database, a header, a label, a theme ID, a test host) is
 * not a rename target at all: in this codebase it is how every persisted or deployed identifier is spelt, so it stays.
 *
 * Environment variables keep working under their old names: every entry point reads `KANTEL_*` and falls back to
 * `HARBOUR_*` (`packages/contracts/src/env.ts`), the deploy workflow reads `vars.KANTEL_* || vars.HARBOUR_*`, and the
 * Compose files `${KANTEL_X:-${HARBOUR_X}}`. Those forms are written by RULES and kept by KEEP, so a second run changes
 * nothing.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

type Keep = {
	/** What is kept, as a regular expression with the `g` flag. */
	readonly pattern: RegExp;
	readonly reason: string;
	/** Only in these files; everywhere when absent. */
	readonly paths?: RegExp;
};

type Rule = {
	readonly id: string;
	readonly pattern: RegExp;
	/** The replacement. `keep` marks text the later rules must not touch. */
	readonly replace: (keep: (text: string) => string, ...match: string[]) => string;
	readonly paths?: RegExp;
	/** Also counted by `--check`: a match left after KEEP is a miss. */
	readonly target?: boolean;
};

// Files the codemod never opens.
const SKIP: readonly { readonly paths: RegExp; readonly reason: string }[] = [
	{
		paths: /(^|\/)(pnpm-lock\.yaml|bun\.lock|package-lock\.json)$/,
		reason: "Lockfiles: regenerated by an install after the package renames, never rewritten by hand.",
	},
	{
		paths: /^apps\/selfhosted\/sql\/.*\.sql$/,
		reason: "Applied SQL migrations: a rename there would be a new migration, and the schema `harbour` is kept.",
	},
	{
		paths: /^packages\/ui\/src\/brand\/artwork\//,
		reason: "The approved Kantel artwork, exactly as approved.",
	},
	{ paths: /^patches\//, reason: "Patches to dependencies: their context must match the upstream source." },
	{ paths: /^tools\/kantel-rename\.ts$/, reason: "This codemod." },
	{
		paths: /\.(png|jpe?g|gif|webp|ico|woff2?|ttf|otf|xlsx|docx|pptx|pdf|zip|gz|wasm)$/i,
		reason: "Binary files.",
	},
];

