const SENTINEL = "\u0000";

/** Rewrites one file's text. Returns the new text and how often each rule fired. */
export function transform(file: string, text: string): { text: string; counts: Map<string, number> } {
	const held: string[] = [];
	const keep = (value: string) => {
		held.push(value);
		return `${SENTINEL}${held.length - 1}${SENTINEL}`;
	};
	let out = text;
	for (const { pattern, paths } of KEEP) if (pathOk(paths, file)) out = out.replace(pattern, (match) => keep(match));
	const counts = new Map<string, number>();
	const historical = HISTORICAL.test(file);
	for (const rule of RULES) {
		if (!pathOk(rule.paths, file)) continue;
		if (historical && !HISTORICAL_RULES.has(rule.id)) continue;
		out = out.replace(rule.pattern, (...args: unknown[]) => {
			counts.set(rule.id, (counts.get(rule.id) ?? 0) + 1);
			const groups = args.slice(0, -2).filter((arg) => typeof arg === "string" || arg === undefined) as string[];
			return rule.replace(keep, ...groups.map((g) => g ?? ""));
		});
	}
	const restore = new RegExp(`${SENTINEL}(\\d+)${SENTINEL}`, "g");
	// A kept value can hold another (a rule's output kept, then matched by KEEP on a later run): unwrap until none.
	while (out.includes(SENTINEL)) out = out.replace(restore, (_m, index: string) => held[Number(index)] ?? "");
	return { text: out, counts };
}

/** What the rename still targets in a file, after KEEP: `--check`'s misses. */
export function misses(file: string, text: string): { line: number; rule: string; text: string }[] {
	if (SKIP.some(({ paths }) => paths.test(file))) return [];
	let masked = text;
	for (const { pattern, paths } of KEEP)
		if (pathOk(paths, file)) masked = masked.replace(pattern, (match) => " ".repeat(match.length));
	const found: { line: number; rule: string; text: string }[] = [];
	const historical = HISTORICAL.test(file);
	for (const rule of RULES) {
		if (rule.target !== true || !pathOk(rule.paths, file)) continue;
		if (historical && !HISTORICAL_RULES.has(rule.id)) continue;
		for (const match of masked.matchAll(rule.pattern)) {
			const index = match.index ?? 0;
			const line = masked.slice(0, index).split("\n").length;
			found.push({ line, rule: rule.id, text: text.split("\n")[line - 1]?.trim().slice(0, 140) ?? "" });
		}
	}
	return found;
}

function trackedTextFiles(): string[] {
	const files = execFileSync("git", ["ls-files", "-z"], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 })
		.split("\0")
		.filter((file) => file !== "");
	return files.filter((file) => !SKIP.some(({ paths }) => paths.test(file)));
}

function readText(file: string): string | undefined {
	let buffer: Buffer;
	try {
		buffer = readFileSync(file);
	} catch {
		return undefined; // Deleted in the working tree.
	}
	if (buffer.includes(0)) return undefined;
	return buffer.toString("utf8");
}

function main(argv: readonly string[]): number {
	const write = argv.includes("--write");
	const check = argv.includes("--check");
	const files = trackedTextFiles();
	if (check) {
		let total = 0;
		for (const file of files) {
			const text = readText(file);
			if (text === undefined) continue;
			for (const miss of misses(file, text)) {
				total += 1;
				console.log(`${file}:${miss.line}: [${miss.rule}] ${miss.text}`);
			}
		}
		const moved = MOVES.filter(([from]) => files.includes(from));
		for (const [from, to] of moved) console.log(`${from}: should be ${to}`);
		total += moved.length;
		console.log(total === 0 ? "kantel-rename --check: clean" : `kantel-rename --check: ${total} left`);
		return total === 0 ? 0 : 1;
	}
	const byRule = new Map<string, number>();
	const byFile: [string, number][] = [];
	for (const file of files) {
		const text = readText(file);
		if (text === undefined) continue;
		const result = transform(file, text);
		if (result.text === text) continue;
		let sum = 0;
		for (const [rule, count] of result.counts) {
			byRule.set(rule, (byRule.get(rule) ?? 0) + count);
			sum += count;
		}
		byFile.push([file, sum]);
		if (write) writeFileSync(file, result.text);
	}
	if (write)
		for (const [from, to] of MOVES)
			if (files.includes(from)) execFileSync("git", ["mv", from, to], { stdio: "inherit" });
	console.log(`${write ? "Changed" : "Would change"} ${byFile.length} files:`);
	for (const [rule, count] of [...byRule].sort((a, b) => b[1] - a[1]))
		console.log(`  ${String(count).padStart(6)}  ${rule}`);
	if (argv.includes("--files"))
		for (const [file, count] of byFile.sort((a, b) => b[1] - a[1]))
			console.log(`  ${String(count).padStart(6)}  ${file}`);
	for (const [from, to] of MOVES)
		if (files.includes(from)) console.log(`  ${write ? "moved" : "would move"} ${from} → ${to}`);
	return 0;
}

if (import.meta.url === `file://${process.argv[1]}`) process.exit(main(process.argv.slice(2)));
