// node packages/hosts/scripts/selkies-web.ts <selkies_web dir> <version>: writes src/selkies-web.ts, the files of
// Selkies' web client the gateway serves for a desktop (desktop.ts) and each one's SHA-256. The directory is
// `selkies/selkies_web` from Selkies' release wheel, the version the guest image installs (SELKIES_VERSION in
// apps/host/guest/Dockerfile):
//
//   gh release download 2.2.0 -R selkies-project/selkies -p 'selkies-2.2.0-py3-none-any.whl'
//   python3 -m zipfile -e selkies-2.2.0-py3-none-any.whl wheel/
//   node packages/hosts/scripts/selkies-web.ts wheel/selkies/selkies_web 2.2.0
//
// Left out: Python files, and jsdb/ (gamepad mappings; the image turns gamepads off).
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const [dir, version] = process.argv.slice(2);
if (dir === undefined || version === undefined) {
	console.error("usage: selkies-web.ts <selkies_web dir> <version>");
	process.exit(2);
}

function walk(at: string): string[] {
	return readdirSync(at).flatMap((name) => {
		const path = join(at, name);
		return statSync(path).isDirectory() ? walk(path) : [path];
	});
}

const files = walk(dir)
	.map((path) => relative(dir, path))
	.filter((path) => !path.startsWith("jsdb/") && !path.startsWith("__pycache__/") && !path.endsWith(".py"))
	.sort();
const lines = files.map((path) => {
	const bytes = readFileSync(join(dir, path));
	return `\t\t${JSON.stringify(path)}: { sha256: "${createHash("sha256").update(bytes).digest("hex")}", size: ${bytes.length} },`;
});
const out = `// Generated by scripts/selkies-web.ts from Selkies ${version}'s release wheel: don't edit by hand.
/** The Selkies web client the gateway serves for a desktop: each file's SHA-256 and size. */
export const SELKIES_WEB = {
	version: ${JSON.stringify(version)},
	files: {
${lines.join("\n")}
	} as { readonly [path: string]: { readonly sha256: string; readonly size: number } },
} as const;
`;
writeFileSync(new URL("../src/selkies-web.ts", import.meta.url), out);
console.log(`${files.length} files`);
