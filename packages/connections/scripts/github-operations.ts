/**
 * Generates `src/github-operations.generated.ts`, GitHub's REST operations (#465), from GitHub's own OpenAPI
 * description (github/rest-api-description, api.github.com). Each operation keeps its method, path, operation ID
 * (`issues/create-comment`), category and subcategory (`x-github`) and summary; `src/operations.ts` reads them into a label,
 * a permission group, an access class and a resource.
 *
 *   node packages/connections/scripts/github-operations.ts [description.json]
 *
 * Without a file it downloads the description from GitHub. Run `pnpm biome format --write` on the output afterwards.
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const SOURCE =
	"https://raw.githubusercontent.com/github/rest-api-description/main/descriptions/api.github.com/api.github.com.json";
const OUT = fileURLToPath(new URL("../src/github-operations.generated.ts", import.meta.url));
const METHODS = ["get", "post", "put", "patch", "delete"] as const;

interface Operation {
	readonly operationId?: string;
	readonly summary?: string;
	readonly "x-github"?: { readonly category?: string; readonly subcategory?: string };
}
interface Description {
	readonly info: { readonly version: string };
	readonly paths: Readonly<Record<string, Readonly<Record<string, Operation>>>>;
}

const file = process.argv[2];
const text = file === undefined ? await (await fetch(SOURCE)).text() : await readFile(file, "utf8");
const description = JSON.parse(text) as Description;

const rows: string[] = [];
for (const [path, item] of Object.entries(description.paths)) {
	for (const method of METHODS) {
		const operation = item[method];
		if (operation?.operationId === undefined) continue;
		const category = operation["x-github"]?.category ?? operation.operationId.split("/")[0] ?? "";
		const subcategory = operation["x-github"]?.subcategory ?? category;
		const summary = (operation.summary ?? operation.operationId).trim();
		rows.push(
			JSON.stringify([method.toUpperCase(), path, operation.operationId, category, subcategory, summary].join(" ")),
		);
	}
}
rows.sort();

const header = `// Generated by scripts/github-operations.ts from GitHub's REST API description ${description.info.version}
// (github/rest-api-description, api.github.com). Do not edit by hand: run the script again.

export const GITHUB_API_VERSION = ${JSON.stringify(description.info.version)};

/**
 * One REST operation per line: its method, path, operation ID, category and subcategory, then its summary, the first
 * five separated by single spaces (none has one of its own), the summary the rest of the line.
 */
export const GITHUB_OPERATIONS: readonly string[] = [
`;
await writeFile(OUT, `${header}${rows.map((row) => `\t${row},`).join("\n")}\n];\n`);
console.log(`${rows.length} operations written to ${OUT}`);
