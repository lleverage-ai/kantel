package kantel

import (
	"os"
	"strings"
	"testing"
)

// The docs' command reference is made from the command table, and must be kept up to date with it.
func TestReferenceIsCurrent(t *testing.T) {
	cwd, _ := os.Getwd()
	path, err := ReferencePath(cwd)
	if err != nil {
		t.Fatal(err)
	}
	current, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if string(current) != Reference(Program().SchemaOf()) {
		t.Fatalf("%s is out of date: run go run ./cmd/kantel-docs in apps/cli", path)
	}
}

func TestReferenceEscapes(t *testing.T) {
	eq(t, "cell", mdText("a <b> & c|d", true), `a &lt;b&gt; &amp; c\|d`)
	eq(t, "prose", mdText("a|b", false), "a|b")
	eq(t, "details", paragraphs("One line\nand more:\n\n  kantel x <id>\nThen <this>."),
		"One line and more:\n\n```sh\nkantel x <id>\n```\n\nThen &lt;this&gt;.")
	page := Reference(Program().SchemaOf())
	for _, want := range []string{"title: Command reference", "    text: Experimental", "<!-- Generated by apps/cli/cmd/kantel-docs",
		"### kantel update", "| `--version <version>` | Install this release, such as 0.2.0 |"} {
		if !strings.Contains(page, want) {
			t.Errorf("the page has no %q", want)
		}
	}
}
