// Writes the docs for language models into the built site (dist/), after `astro build`:
// - /docs/<page>.md: each docs page as plain Markdown (frontmatter and source comments taken out, links made absolute
//   and pointed at the other pages' .md), so an agent can read a page without its HTML;
// - /docs/llms.txt: the index, in https://llmstxt.org form: what Kantel is, then every page in sidebar order, under
//   the sidebar's group labels, with its description;
// - /docs/llms-full.txt: every page's Markdown in one file.
// It reads the pages from docs/site, the same source scripts/sync-docs.mjs copies, and the sidebar from
// docs/site/sidebar.mjs, so a page appears here exactly when it's in the sidebar.

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { sidebar } from "../../../docs/site/sidebar.mjs";
import { SITE_URL } from "../src/site.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "../../../docs/site/src/content/docs");
const dist = join(here, "../dist/docs");
const DOCS_URL = `${SITE_URL}/docs`;

/** A page's frontmatter fields this script needs, and its body. Frontmatter here is flat YAML written by people. */
export function parsePage(text) {
	const match = /^---\n([\s\S]*?)\n---\n/.exec(text);
	if (match === null)
		return { title: undefined, description: undefined, order: undefined, badge: undefined, body: text };
	const front = match[1];
	const field = (name) => {
		const line = new RegExp(`^${name}:\\s*(.+)$`, "m").exec(front)?.[1]?.trim();
		if (line === undefined) return undefined;
		return line.startsWith('"') ? JSON.parse(line) : line;
	};
	const order = /^\s+order:\s*(\d+)/m.exec(front)?.[1];
	const badge = /^\s+text:\s*(.+)$/m.exec(front)?.[1]?.trim();
	return {
		title: field("title"),
		description: field("description"),
		order: order === undefined ? undefined : Number(order),
		badge,
		body: text.slice(match[0].length),
	};
}

/** A page slug's Markdown URL: `concepts` is /docs/concepts.md, the home page /docs/index.md. */
const markdownUrl = (slug) => `${DOCS_URL}/${slug === "" ? "index" : slug}.md`;

/**
 * The body for an agent: HTML comments (each page's sources) dropped, and root-relative links made absolute, to the
 * linked page's .md when it's a page, keeping any #fragment.
 */
export function forAgents(body) {
	return body
		.replace(/<!--[\s\S]*?-->\n?/g, "")
		.replace(/\]\(\/([^)\s#]*?)\/?(#[^)\s]*)?\)/g, (_, path, fragment = "") => `](${markdownUrl(path)}${fragment})`)
		.trim();
}

/** Every docs page's slug under a directory of the docs, ordered as Starlight's autogenerated group orders them. */
function directoryPages(directory) {
	const dir = join(source, directory);
	return readdirSync(dir)
		.filter((name) => /\.mdx?$/.test(name))
		.map((name) => {
			const slug = `${directory}/${name.replace(/\.mdx?$/, "")}`.replace(/\/index$/, "");
			return { slug, page: parsePage(readFileSync(join(dir, name), "utf8")) };
		})
		.sort((a, b) => (a.page.order ?? 999) - (b.page.order ?? 999) || a.slug.localeCompare(b.slug))
		.map(({ slug }) => slug);
}

/** The page slugs of one sidebar entry, in order. */
function entrySlugs(entry) {
	if (typeof entry === "string") return [entry];
	if ("link" in entry) return entry.link.startsWith("/") ? [entry.link.replace(/^\/|\/$/g, "")] : [];
	if ("autogenerate" in entry) return directoryPages(entry.autogenerate.directory);
	if ("items" in entry) return entry.items.flatMap(entrySlugs);
	return [];
}

function readPage(slug) {
	const candidates =
		slug === "" ? ["index.md", "index.mdx"] : [`${slug}.md`, `${slug}.mdx`, `${slug}/index.md`, `${slug}/index.mdx`];
	for (const candidate of candidates) {
		const path = join(source, candidate);
		if (existsSync(path)) return parsePage(readFileSync(path, "utf8"));
	}
	throw new Error(`llms-txt: the sidebar names ${slug || "the home page"}, but docs/site has no page for it`);
}

const intro = [
	"# Kantel",
	"",
	"> Kantel, by Lleverage, is a compute plane for AI agents that you can run yourself: it gives agents sandboxes (lightweight isolates, or Firecracker microVMs with root, Docker and /dev/kvm) on Linux hosts that join with one command. Drive it with the HTTP API, the TypeScript SDK, the `kantel` CLI or its MCP server.",
	"",
	`Every page below is Markdown. The same page as HTML is at the URL without \`.md\`, under ${DOCS_URL}/. Everything in one file: ${DOCS_URL}/llms-full.txt.`,
	"",
	"Pages marked (experimental) describe parts of Kantel still being built.",
];

const index = [...intro];
const full = [...intro];
let pages = 0;
for (const group of sidebar) {
	const slugs = entrySlugs(group);
	if (slugs.length === 0) continue;
	index.push("", `## ${group.label}`, "");
	for (const slug of slugs) {
		const page = readPage(slug);
		const title = page.title ?? slug;
		const experimental = page.badge === "Experimental" ? " (experimental)" : "";
		index.push(`- [${title}](${markdownUrl(slug)})${experimental}${page.description ? `: ${page.description}` : ""}`);
		const markdown = [
			`# ${title}`,
			"",
			...(page.description ? [`> ${page.description}`, ""] : []),
			forAgents(page.body),
			"",
		];
		const out = join(dist, `${slug === "" ? "index" : slug}.md`);
		mkdirSync(dirname(out), { recursive: true });
		writeFileSync(out, markdown.join("\n"));
		full.push("", "---", "", `Source: ${markdownUrl(slug)}`, "", ...markdown);
		pages++;
	}
}

mkdirSync(dist, { recursive: true });
writeFileSync(join(dist, "llms.txt"), `${index.join("\n")}\n`);
writeFileSync(join(dist, "llms-full.txt"), `${full.join("\n").trimEnd()}\n`);
console.log(`llms-txt: ${pages} pages as Markdown, with docs/llms.txt and docs/llms-full.txt`);
