// Copies the hero's pixel field (../src/scripts/pixel-field.js) into this folder as a classic script, so the video's
// background is the site's own animation. The renderer opens index.html from file://, where Chrome won't load an ES
// module, so the copy drops `export` and hangs mountPixelField on window. Run it after changing the original:
//   node apps/site/video/sync-pixel-field.mjs
import { readFileSync, writeFileSync } from "node:fs";

const source = readFileSync(new URL("../src/scripts/pixel-field.js", import.meta.url), "utf8");
if (!source.includes("export function mountPixelField"))
	throw new Error("pixel-field.js no longer exports mountPixelField");
const body = source.replace("export function mountPixelField", "function mountPixelField");
writeFileSync(
	new URL("pixel-field.js", import.meta.url),
	`// Generated by sync-pixel-field.mjs from ../src/scripts/pixel-field.js. Don't edit: change the original.\n(() => {\n${body}\nwindow.mountPixelField = mountPixelField;\n})();\n`,
);
